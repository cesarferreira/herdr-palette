pub(crate) fn documentation(
    id: &str,
    title: &str,
    description: &str,
    aliases: &[&str],
    shortcuts: &[&str],
    category: Category,
) -> PaletteItem {
    PaletteItem {
        id: id.into(),
        title: title.into(),
        category,
        description: description.into(),
        aliases: aliases.iter().map(|value| (*value).into()).collect(),
        shortcuts: shortcuts.iter().map(|value| (*value).into()).collect(),
        invocation: Invocation::DocumentationOnly,
    }
}

fn action(
    id: &str,
    title: &str,
    category: Category,
    description: &str,
    aliases: &[&str],
    shortcuts: &[&str],
    argv: &[&str],
) -> PaletteItem {
    PaletteItem {
        id: id.into(),
        title: title.into(),
        category,
        description: description.into(),
        aliases: aliases.iter().map(|value| (*value).into()).collect(),
        shortcuts: shortcuts.iter().map(|value| (*value).into()).collect(),
        invocation: Invocation::Herdr(argv.iter().map(|value| (*value).into()).collect()),
    }
}
