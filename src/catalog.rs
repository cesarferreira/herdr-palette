#[derive(Clone, Debug, PartialEq, Eq)]
pub enum Category {
    Workspace,
    Tab,
    Pane,
    Application,
    Custom,
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub enum Invocation {
    Herdr(Vec<String>),
    DocumentationOnly,
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct PaletteItem {
    pub id: String,
    pub title: String,
    pub category: Category,
    pub description: String,
    pub aliases: Vec<String>,
    pub shortcuts: Vec<String>,
    pub invocation: Invocation,
}

